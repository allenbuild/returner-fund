function momentum(currentScore: number, currentRank: number) {
  return {
    scoreDelta: 0,
    percentDelta: 0,
    rankDelta: 0,
    currentScore,
    currentRank,
    baselineScore: null as number | null,
    baselineRank: null as number | null,
    benchmarkedAt: null as string | null
  };
}

function addTiedCompany(graph: ValidSnapshot) {
  const evidence = structuredClone(graph.evidence[0]!);
  const socialAccount = fixtureSocialAccount(
    "company",
    "company-2",
    "x",
    "https://x.com/companytwo"
  );
  evidence.id = "evidence-2";
  evidence.entityId = "company-2";
  evidence.attachedCompanyId = "company-2";
  evidence.authorName = "Company Two";
  evidence.authorHandle = "companytwo";
  evidence.sourceUrl = "https://x.com/companytwo/status/2";
  evidence.socialAccountId = socialAccount.id;

  const node = structuredClone(graph.nodes[0]!);
  node.id = "company:company-2";
  node.entityId = "company-2";
  node.label = "Company Two";
  node.socialAccounts = [socialAccount];
  node.evidenceIds = [evidence.id];

  graph.batch.companyCountObserved = 2;
  graph.evidence.push(evidence);
  graph.nodes.push(node);
  graph.leaderboard.push({
    rank: 1,
    companyId: "company-2",
    companyName: "Company Two",
    score: 13,
    topPlatform: "x",
    biggestContribution: evidence
  });
  graph.fastestGaining.push({
    rank: 2,
    companyId: "company-2",
    companyName: "Company Two",
    dod: momentum(13, 1),
    wow: momentum(13, 1)
  });
}

function graphWithEdges(graph: ValidSnapshot) {
  return graph as unknown as {
    edges: Array<{
      id: string;
      source: string;
      target: string;
      edgeType: string;
      weight: number;
      label: string;
      explanation: string;
    }>;
  };
}

function fixtureSocialAccount(
  entityType: "company" | "founder",
  entityId: string,
  platform: string,
  url: string
) {
  return {
    id: materializedSocialAccountId(entityType, entityId, platform, url),
    platform,
    handle: url.split("/").at(-1) ?? null,
    url,
    review_state: "verified" as const,
    discoveredFromUrl: null,
    matchReason: "Canonical lineage fixture."
  };
}

function materializedSocialAccountId(
  entityType: "company" | "founder",
  entityId: string,
  platform: string,
  canonicalUrl: string
) {
  return `acct:${entityType}:${entityId}:${platform}:${encodeURIComponent(canonicalUrl)}`;
}

type FixtureSocialAccount = ReturnType<typeof fixtureSocialAccount>;
type FixtureFounder = { id: string; socialAccounts: FixtureSocialAccount[] };

type ValidSnapshot = ReturnType<typeof validSnapshot>;
