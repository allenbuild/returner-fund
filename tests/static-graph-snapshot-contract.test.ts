import { describe, expect, it } from "vitest";
import { buildGraphResponse } from "@/lib/graph/graph-builder";
import { sanitizeGraphResponse } from "@/lib/graph/response-sanitizer";
import {
  formatStaticGraphSnapshotContractIssue,
  validateStaticGraphSnapshotContract
} from "@/lib/graph/static-graph-snapshot-contract.mjs";
import { yc2026GraphDataset } from "@/lib/graph/yc-spring-2026-dataset";
import type { TopVoiceAudienceId } from "@/lib/graph/types";

const VALIDATION_NOW = new Date("2026-07-16T12:00:00.000Z");
const MISMATCHED_PLATFORM_WEIGHT_CASES = [
  { platform: "x", configuredWeight: 0.24, canonicalWeight: 0.21 },
  { platform: "instagram", configuredWeight: 0.18, canonicalWeight: 0.21 },
  { platform: "linkedin", configuredWeight: 0.16, canonicalWeight: 0.15 },
  { platform: "github", configuredWeight: 0.14, canonicalWeight: 0.15 },
  { platform: "youtube", configuredWeight: 0.11, canonicalWeight: 0.1 },
  { platform: "product_hunt", configuredWeight: 0.08, canonicalWeight: 0.07 },
  { platform: "hacker_news", configuredWeight: 0.06, canonicalWeight: 0.05 },
  { platform: "reddit", configuredWeight: 0.03, canonicalWeight: 0.04 },
  { platform: "bilibili", configuredWeight: 0.01, canonicalWeight: 0.02 }
] as const;

describe("canonical v4 static graph snapshot contract", () => {
  it("accepts all nine graph variants generated by the current v4 builder", () => {
    const batchSlugs = ["S2026", "S26", "A16ZSR006"];
    const audiences: TopVoiceAudienceId[] = ["off", "yc_partners", "insiders"];

    for (const batchSlug of batchSlugs) {
      for (const topVoices of audiences) {
        const graph = sanitizeGraphResponse(
          buildGraphResponse({ batchSlug, topVoices }, yc2026GraphDataset)
        );
        const result = validateStaticGraphSnapshotContract(graph);
        const detail = result.ok
          ? ""
          : result.issues.slice(0, 3).map(formatStaticGraphSnapshotContractIssue).join("; ");

        expect(result, `${batchSlug}/${topVoices}: ${detail}`).toEqual({ ok: true, issues: [] });
      }
    }
  });

  it("accepts a complete minimal snapshot", () => {
    expect(
      validateStaticGraphSnapshotContract(validSnapshot(), {
        now: VALIDATION_NOW,
        maxFutureSkewMs: 0
      })
    ).toEqual({ ok: true, issues: [] });
  });

  it.each(MISMATCHED_PLATFORM_WEIGHT_CASES)(
    "rejects configured weight drift for $platform",
    ({ platform, configuredWeight, canonicalWeight }) => {
      const graph = validSnapshot();
      graph.nodes[0]!.scoreBreakdown.weightedPlatforms[0]!.platform = platform;
      graph.nodes[0]!.scoreBreakdown.weightedPlatforms[0]!.configuredWeight = configuredWeight;
      graph.nodes[0]!.topPlatform = platform;
      graph.leaderboard[0]!.topPlatform = platform;

      const result = validateStaticGraphSnapshotContract(graph, {
        now: VALIDATION_NOW,
        maxFutureSkewMs: 0
      });

      expect(result.ok).toBe(false);
      if (!result.ok) {
        expect(result.issues).toContainEqual({
          path: "nodes[0].scoreBreakdown.weightedPlatforms[0].configuredWeight",
          message: `must equal canonical v4 weight ${canonicalWeight} for ${platform}`
        });
      }
    }
  );

  it("accepts a filtered Top Voice snapshot with canonical score state and full-cohort rank gaps", () => {
    const graph = validSnapshot();
    graph.selectedTopVoiceAudience.id = "insiders";
    Object.assign(graph.nodes[0]!, {
      selectedTopVoiceAudience: { id: "insiders" },
      topVoiceConnectionCount: 1
    });
    Object.assign(graph.evidence[0]!, {
      topVoice: {
        audienceId: "insiders",
        originalContributionScore: graph.evidence[0]!.contributionScore
      }
    });
    graph.leaderboard[0]!.rank = 3;
    graph.fastestGaining[0]!.rank = 4;
    graph.fastestGaining[0]!.dod.currentRank = 3;
    graph.fastestGaining[0]!.wow.currentRank = 3;

    expect(
      validateStaticGraphSnapshotContract(graph, {
        now: VALIDATION_NOW,
        maxFutureSkewMs: 0
      })
    ).toEqual({ ok: true, issues: [] });
  });

  it("accepts explicit null account lineage without a materialized account", () => {
    const graph = validSnapshot();
    graph.evidence[0]!.socialAccountId = null;
    graph.nodes[0]!.socialAccounts = [];

    expect(
      validateStaticGraphSnapshotContract(graph, {
        now: VALIDATION_NOW,
        maxFutureSkewMs: 0
      })
    ).toEqual({ ok: true, issues: [] });
  });

  it.each([
    {
      name: "dangling account lineage",
      path: "evidence[0].socialAccountId",
      mutate: (graph: ValidSnapshot) => {
        graph.evidence[0]!.socialAccountId = materializedSocialAccountId(
          "company",
          "company-1",
          "x",
          "https://x.com/missing"
        );
      }
    },
    {
      name: "wrong-owner account lineage",
      path: "evidence[0].socialAccountId",
      mutate: (graph: ValidSnapshot) => {
        const account = fixtureSocialAccount(
          "founder",
          "founder-1",
          "x",
          "https://x.com/founderone"
        );
        graph.nodes[0]!.socialAccounts = [];
        graph.nodes[0]!.founders.push({ id: "founder-1", socialAccounts: [account] });
        graph.evidence[0]!.socialAccountId = account.id;
      }
    },
    {
      name: "wrong-platform account lineage",
      path: "evidence[0].socialAccountId",
      mutate: (graph: ValidSnapshot) => {
        const account = fixtureSocialAccount(
          "company",
          "company-1",
          "github",
          "https://github.com/companyone"
        );
        graph.nodes[0]!.socialAccounts = [account];
        graph.evidence[0]!.socialAccountId = account.id;
      }
    },
    {
      name: "materialized account ID collision",
      path: "nodes[0].socialAccounts[1].id",
      mutate: (graph: ValidSnapshot) => {
        graph.nodes[0]!.socialAccounts.push(
          structuredClone(graph.nodes[0]!.socialAccounts[0]!)
        );
      }
    },
    {
      name: "fabricated account ID",
      path: "nodes[0].socialAccounts[0].id",
      mutate: (graph: ValidSnapshot) => {
        graph.nodes[0]!.socialAccounts[0]!.id = "fabricated-account-id";
        graph.evidence[0]!.socialAccountId = "fabricated-account-id";
      }
    }
  ])("rejects $name", ({ path, mutate }) => {
    const graph = validSnapshot();
    mutate(graph);

    const result = validateStaticGraphSnapshotContract(graph, {
      now: VALIDATION_NOW,
      maxFutureSkewMs: 0
    });

    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.issues.some((issue) => issue.path === path), JSON.stringify(result.issues)).toBe(true);
    }
  });

  it.each([
    {
      name: "out-of-range node score",
      path: "nodes[0].score",
      mutate: (graph: ValidSnapshot) => { graph.nodes[0]!.score = 101; }
    },
    {
      name: "node and total score mismatch",
      path: "nodes[0].score",
      mutate: (graph: ValidSnapshot) => { graph.nodes[0]!.scoreBreakdown.totalScore = 63; }
    },
    {
      name: "out-of-range absolute score",
      path: "nodes[0].scoreBreakdown.absoluteScore",
      mutate: (graph: ValidSnapshot) => { graph.nodes[0]!.scoreBreakdown.absoluteScore = -1; }
    },
    {
      name: "out-of-range calibration input",
      path: "nodes[0].scoreBreakdown.calibration.inputScore",
      mutate: (graph: ValidSnapshot) => { graph.nodes[0]!.scoreBreakdown.calibration.inputScore = 101; }
    },
    {
      name: "out-of-range calibration percentile",
      path: "nodes[0].scoreBreakdown.calibration.percentile",
      mutate: (graph: ValidSnapshot) => {
        (graph.nodes[0]!.scoreBreakdown.calibration as { percentile: number | null }).percentile = 1.1;
      }
    },
    {
      name: "out-of-range platform score",
      path: "nodes[0].scoreBreakdown.platformScores.x",
      mutate: (graph: ValidSnapshot) => { graph.nodes[0]!.scoreBreakdown.platformScores.x = 101; }
    },
    {
      name: "out-of-range evidence score",
      path: "evidence[0].contributionScore",
      mutate: (graph: ValidSnapshot) => { graph.evidence[0]!.contributionScore = 101; }
    },
    {
      name: "rejected positive evidence",
      path: "evidence[0].review_state",
      mutate: (graph: ValidSnapshot) => { graph.evidence[0]!.review_state = "rejected"; }
    },
    {
      name: "unscored positive evidence",
      path: "evidence[0].tractionStatus",
      mutate: (graph: ValidSnapshot) => { graph.evidence[0]!.tractionStatus = "unscored"; }
    },
    {
      name: "explicitly noneligible positive evidence",
      path: "evidence[0]",
      mutate: (graph: ValidSnapshot) => { graph.evidence[0]!.score_eligible = false; }
    },
    {
      name: "dated confidence count above scored count",
      path: "nodes[0].scoreBreakdown.confidence.datedEvidenceCount",
      mutate: (graph: ValidSnapshot) => { graph.nodes[0]!.scoreBreakdown.confidence.datedEvidenceCount = 2; }
    },
    {
      name: "verified confidence count above scored count",
      path: "nodes[0].scoreBreakdown.confidence.verifiedLinkCount",
      mutate: (graph: ValidSnapshot) => { graph.nodes[0]!.scoreBreakdown.confidence.verifiedLinkCount = 2; }
    },
    {
      name: "scored confidence count above referenced evidence",
      path: "nodes[0].scoreBreakdown.confidence.scoredEvidenceCount",
      mutate: (graph: ValidSnapshot) => { graph.nodes[0]!.scoreBreakdown.confidence.scoredEvidenceCount = 2; }
    },
    {
      name: "leaderboard and node score mismatch",
      path: "leaderboard[0].score",
      mutate: (graph: ValidSnapshot) => { graph.leaderboard[0]!.score = 62; }
    },
    {
      name: "future snapshot timestamps",
      path: "generatedAt",
      mutate: (graph: ValidSnapshot) => {
        graph.generatedAt = "2026-07-16T12:00:01.000Z";
        graph.scoringContext.responseBuiltAt = graph.generatedAt;
      }
    },
    {
      name: "response build time drift",
      path: "scoringContext.responseBuiltAt",
      mutate: (graph: ValidSnapshot) => {
        graph.scoringContext.responseBuiltAt = "2026-07-16T05:00:01.000Z";
      }
    },
    {
      name: "future evidence publication time",
      path: "evidence[0].postedAt",
      mutate: (graph: ValidSnapshot) => {
        graph.evidence[0]!.postedAt = "2026-07-16T05:00:01.000Z";
      }
    },
    {
      name: "audience and scoring scope drift",
      path: "scoringContext.scoreScope",
      mutate: (graph: ValidSnapshot) => { graph.scoringContext.scoreScope = "top_voice"; }
    },
    {
      name: "selected platform scoring context drift",
      path: "scoringContext.selectedPlatforms",
      mutate: (graph: ValidSnapshot) => { graph.scoringContext.selectedPlatforms = ["x"]; }
    },
    {
      name: "Top Voice member-weighted evidence",
      path: "evidence[0].contributionScore",
      mutate: (graph: ValidSnapshot) => {
        Object.assign(graph.evidence[0]!, {
          contributionScore: 80,
          topVoice: { audienceId: "insiders", originalContributionScore: 64 }
        });
      }
    },
    {
      name: "incoherent node identity",
      path: "nodes[0].id",
      mutate: (graph: ValidSnapshot) => { graph.nodes[0]!.id = "company:somebody-else"; }
    },
    {
      name: "node outside the batch scope",
      path: "nodes[0].batchSlug",
      mutate: (graph: ValidSnapshot) => { graph.nodes[0]!.batchSlug = "S26"; }
    },
    {
      name: "edge with a missing endpoint",
      path: "edges[0].target",
      mutate: (graph: ValidSnapshot) => {
        graphWithEdges(graph).edges = [{
          id: "edge-1",
          source: "company:company-1",
          target: "company:missing",
          edgeType: "industry_similarity",
          weight: 0.5,
          label: "Industry similarity",
          explanation: "Fixture edge."
        }];
      }
    },
    {
      name: "ordinal rank for a tied score",
      path: "leaderboard[1].rank",
      mutate: (graph: ValidSnapshot) => {
        addTiedCompany(graph);
        graph.leaderboard[1]!.rank = 2;
      }
    },
    {
      name: "momentum row identity drift",
      path: "fastestGaining[0].companyId",
      mutate: (graph: ValidSnapshot) => { graph.fastestGaining[0]!.companyId = "company-missing"; }
    },
    {
      name: "momentum current score drift",
      path: "fastestGaining[0].dod.currentScore",
      mutate: (graph: ValidSnapshot) => { graph.fastestGaining[0]!.dod.currentScore = 63; }
    },
    {
      name: "momentum current tied-rank drift",
      path: "fastestGaining[1].wow.currentRank",
      mutate: (graph: ValidSnapshot) => {
        addTiedCompany(graph);
        graph.fastestGaining[1]!.wow.currentRank = 2;
      }
    },
    {
      name: "half-null momentum baseline",
      path: "fastestGaining[0].dod.baselineRank",
      mutate: (graph: ValidSnapshot) => { graph.fastestGaining[0]!.dod.baselineRank = 2; }
    },
    {
      name: "nonzero delta without a baseline",
      path: "fastestGaining[0].dod.scoreDelta",
      mutate: (graph: ValidSnapshot) => { graph.fastestGaining[0]!.dod.scoreDelta = 1; }
    },
    {
      name: "incorrect score delta",
      path: "fastestGaining[0].dod.scoreDelta",
      mutate: (graph: ValidSnapshot) => {
        Object.assign(graph.fastestGaining[0]!.dod, {
          baselineScore: 60,
          baselineRank: 2,
          scoreDelta: 3,
          percentDelta: 6.7,
          rankDelta: 1
        });
      }
    },
    {
      name: "incorrect percent delta",
      path: "fastestGaining[0].dod.percentDelta",
      mutate: (graph: ValidSnapshot) => {
        Object.assign(graph.fastestGaining[0]!.dod, {
          baselineScore: 60,
          baselineRank: 2,
          scoreDelta: 4,
          percentDelta: 7,
          rankDelta: 1
        });
      }
    },
    {
      name: "incorrect rank delta",
      path: "fastestGaining[0].dod.rankDelta",
      mutate: (graph: ValidSnapshot) => {
        Object.assign(graph.fastestGaining[0]!.dod, {
          baselineScore: 60,
          baselineRank: 2,
          scoreDelta: 4,
          percentDelta: 6.7,
          rankDelta: 0
        });
      }
    },
    {
      name: "future benchmark timestamp",
      path: "fastestGaining[0].dod.benchmarkedAt",
      mutate: (graph: ValidSnapshot) => {
        graph.fastestGaining[0]!.dod.benchmarkedAt = "2026-07-16T05:00:01.000Z";
      }
    }
  ])("rejects $name", ({ path, mutate }) => {
    const graph = validSnapshot();
    mutate(graph);

    const result = validateStaticGraphSnapshotContract(graph, {
      now: VALIDATION_NOW,
      maxFutureSkewMs: 0
    });

    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.issues.some((issue) => issue.path === path), JSON.stringify(result.issues)).toBe(true);
    }
  });
});

